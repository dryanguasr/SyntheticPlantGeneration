def _resolve_reproductive_pose(
    node_position: object,
    unit: ReproductiveUnit,
    scale: float,
    collision_context: dict[str, Any],
) -> tuple[object, dict[str, Any]]:
    azimuth_offsets = (0.0, 20.0, -20.0, 42.0, -42.0, 66.0, -66.0, 96.0, -96.0)
    angle_offsets = (0.0, 7.0, -7.0)
    best: dict[str, Any] | None = None
    candidate_index = 0

    for azimuth_offset in azimuth_offsets:
        for angle_offset in angle_offsets:
            direction = _reproductive_direction(unit, azimuth_offset, angle_offset)
            score, physical, visual = _score_calyx_pose(
                node_position=node_position,
                unit=unit,
                direction=direction,
                scale=scale,
                collision_context=collision_context,
            )
            score += abs(azimuth_offset) * 0.015 + abs(angle_offset) * 0.025
            candidate = {
                "direction": direction,
                "score": score,
                "physical_collisions": physical,
                "visual_occlusions": visual,
                "retries": candidate_index,
            }
            if best is None or candidate["score"] < best["score"]:
                best = candidate
            if not physical and score < 1.0:
                best = candidate
                break
            candidate_index += 1
        if best is not None and not best["physical_collisions"] and best["score"] < 1.0:
            break

    if best is None:
        best = {
            "direction": _reproductive_direction(unit, 0.0, 0.0),
            "score": 0.0,
            "physical_collisions": [],
            "visual_occlusions": [],
            "retries": 0,
        }
    return best["direction"], {
        "retries": best["retries"],
        "physical_collisions": best["physical_collisions"],
        "visual_occlusions": best["visual_occlusions"][:6],
    }


def _reproductive_direction(
    unit: ReproductiveUnit,
    azimuth_offset_deg: float,
    angle_offset_deg: float,
) -> object:
    _, Vector = _blender_modules()
    radial = _radial_vector(unit.pedicel.azimuth_deg + azimuth_offset_deg)
    angle_deg = max(5.0, min(72.0, unit.pedicel.angle_deg + angle_offset_deg))
    downward = math.sin(math.radians(angle_deg))
    outward = math.cos(math.radians(angle_deg))
    return (radial * outward + Vector((0.0, 0.0, -downward))).normalized()


def _score_calyx_pose(
    node_position: object,
    unit: ReproductiveUnit,
    direction: object,
    scale: float,
    collision_context: dict[str, Any],
) -> tuple[float, list[dict[str, Any]], list[dict[str, Any]]]:
    _, Vector = _blender_modules()
    if unit.calyx is None:
        return 0.0, [], []

    node = Vector(node_position)
    direction = Vector(direction)
    pedicel_end = node + direction * (unit.pedicel.length_cm * scale)
    calyx_length = unit.calyx.length_cm * scale
    calyx_radius = unit.calyx.radius_cm * scale
    center = pedicel_end + direction * (
        calyx_length * CALYX_CENTER_FROM_PEDICEL_FRACTION
    )
    proxy_radius = _calyx_collision_radius(
        calyx_radius,
        calyx_length,
        unit.calyx.inflation,
    )
    score = 0.0
    physical_collisions: list[dict[str, Any]] = []
    visual_occlusions: list[dict[str, Any]] = []

    for segment in collision_context["segments"]:
        distance = _distance_point_to_segment(center, segment["start"], segment["end"])
        minimum = proxy_radius + segment["radius"] + 0.015
        if distance < minimum:
            overlap = minimum - distance
            collision = {
                "type": f"capacho_{segment['kind']}_intersection",
                "calyx_id": unit.calyx.id,
                "other": segment["name"],
                "distance": round(distance, 4),
                "minimum": round(minimum, 4),
            }
            physical_collisions.append(collision)
            score += 60.0 + overlap * 220.0

    for proxy in collision_context["calyx_proxies"]:
        distance = (center - proxy["center"]).length
        minimum = proxy_radius + proxy["radius"] + 0.018
        if distance < minimum:
            overlap = minimum - distance
            physical_collisions.append(
                {
                    "type": "capacho_capacho_intersection",
                    "calyx_id": unit.calyx.id,
                    "other": proxy["name"],
                    "distance": round(distance, 4),
                    "minimum": round(minimum, 4),
                }
            )
            score += 42.0 + overlap * 160.0

    for proxy in collision_context["leaf_proxies"]:
        distance = (center - proxy["center"]).length
        visual_minimum = proxy_radius + proxy["radius"]
        if distance < visual_minimum:
            visual_occlusions.append(
                {
                    "type": "leaf_capacho_visual_occlusion",
                    "calyx_id": unit.calyx.id,
                    "leaf_id": proxy["name"],
                    "distance": round(distance, 4),
                }
            )
            score += (visual_minimum - distance) * 2.2
        physical_minimum = min(proxy_radius, proxy["radius"]) * 0.45
        if distance < physical_minimum:
            physical_collisions.append(
                {
                    "type": "capacho_leaf_deep_intersection",
                    "calyx_id": unit.calyx.id,
                    "leaf_id": proxy["name"],
                    "distance": round(distance, 4),
                    "minimum": round(physical_minimum, 4),
                }
            )
            score += 25.0 + (physical_minimum - distance) * 120.0

    return score, physical_collisions, visual_occlusions


def _calyx_collision_radius(
    calyx_radius: float,
    calyx_length: float,
    inflation: float,
) -> float:
    # Conservative outer envelope; v2's 0.68 multiplier systematically
    # under-estimated green husks and allowed visible interpenetration.
    return max(calyx_radius * inflation * 1.04, calyx_length * 0.27)


def _distance_point_to_segment(point: object, start: object, end: object) -> float:
    _, Vector = _blender_modules()
    point = Vector(point)
    start = Vector(start)
    end = Vector(end)
    segment = end - start
    length_squared = segment.length_squared
    if length_squared <= 1e-10:
        return (point - start).length
    t = max(0.0, min(1.0, (point - start).dot(segment) / length_squared))
    closest = start + segment * t
    return (point - closest).length


def _leaf_gravity_sag(direction: object, length: float) -> float:
    flatness = max(0.0, min(1.0, 1.0 - abs(direction.z)))
    return length * 0.10 * (flatness**1.35)


