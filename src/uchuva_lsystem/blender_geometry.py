def _create_flower_corolla(
    name: str,
    location: object,
    direction: object,
    radius: float,
    material: object,
) -> object:
    bpy, Vector = _blender_modules()
    vertices: list[tuple[float, float, float]] = [(0.0, 0.0, -radius * 0.08)]
    faces: list[tuple[int, int, int, int]] = []
    for petal_index in range(5):
        angle = math.tau * petal_index / 5.0
        left = angle - 0.46
        right = angle + 0.46
        inner_radius = radius * 0.22
        outer_radius = radius * 1.05
        left_index = len(vertices)
        vertices.extend(
            [
                (math.cos(left) * inner_radius, math.sin(left) * inner_radius, 0.0),
                (math.cos(angle) * outer_radius, math.sin(angle) * outer_radius, radius * 0.10),
                (math.cos(right) * inner_radius, math.sin(right) * inner_radius, 0.0),
            ]
        )
        faces.append((0, left_index, left_index + 1, left_index + 2))
    mesh = bpy.data.meshes.new(f"{name}_mesh")
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    corolla = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(corolla)
    corolla.location = Vector(location)
    corolla.data.materials.append(material)
    _orient_local_z_to(corolla, direction)
    solidify = corolla.modifiers.new(name="flower_minimum_thickness", type="SOLIDIFY")
    solidify.thickness = max(radius * 0.035, 0.0015)
    solidify.offset = 0.0
    return corolla


def _visible_fruit_scale(visibility: str, cover_fraction: float) -> float:
    if visibility == "hidden" or cover_fraction >= 0.96:
        return 0.9
    if visibility == "partial":
        return 0.96 if cover_fraction >= 0.88 else 1.0
    if visibility == "visible":
        return 1.03
    return 1.0


