def _register_leaf_proxy(
    context: dict[str, Any],
    name: str,
    base: object,
    direction: object,
    length: float,
    width: float,
    gravity_sag: float,
) -> None:
    _, Vector = _blender_modules()
    base = Vector(base)
    direction = Vector(direction).normalized()
    for t in (0.36, 0.62, 0.84):
        _, y, z = _leaf_centerline_point(t, length, gravity_sag)
        profile, basal_lobes = _leaf_shape_profile("ovate", t)
        center = base + direction * y + Vector((0.0, 0.0, z))
        context["leaf_proxies"].append(
            {
                "kind": "leaf",
                "name": name,
                "center": center,
                "radius": max(width * profile * basal_lobes * 0.24, length * 0.055),
            }
        )


