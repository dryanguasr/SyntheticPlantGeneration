"""Blender geometry interpretation for uchuva morphology trees.

This module reads the morphology tree generated by ``grammar.py`` and creates
preview geometry. It does not decide where organs exist; it only interprets
axes, nodes, leaves, pedicels, calyxes, and fruits already present in the tree.
"""

from __future__ import annotations

import math
import random
from typing import Any

from .blender_annotations import tag_annotation_object
from .morphology import Axis, Leaf, Plant, ReproductiveUnit

CM_TO_BLENDER_UNIT = 0.08
CALYX_CENTER_FROM_PEDICEL_FRACTION = 0.5


def describe_geometry_plan(plant: Plant) -> dict[str, Any]:
    """Return a non-Blender summary of geometry that would be generated."""
    axis_count = sum(_count_axes(axis) for axis in plant.axes)
    return {
        "plant_seed": plant.seed,
        "axes": axis_count,
        "nodes": plant.node_count(),
        "reproductive_units": plant.reproductive_unit_count(),
        "status": "geometry_preview_available",
    }


def build_geometry_from_morphology(
    plant: Plant,
    materials: dict[str, object],
    cm_to_blender_unit: float = CM_TO_BLENDER_UNIT,
    *,
    instance_id: str | None = None,
    instance_role: str = "foreground",
    position: tuple[float, float, float] = (0.0, 0.0, 0.0),
    rotation_deg: float = 0.0,
    plant_scale: float = 1.0,
    add_ground: bool = True,
) -> dict[str, Any]:
    """Build a Blender preview scene from a generated morphology tree."""
    bpy, Vector = _blender_modules()
    from mathutils import Matrix
    instance_transform = Matrix.Identity(4)

    collection = None
    parent_empty = None
    if instance_id is not None:
        collection = bpy.data.collections.new(f"uchuva_{instance_id}")
        bpy.context.scene.collection.children.link(collection)
        parent_empty = bpy.data.objects.new(f"uchuva_{instance_id}_root", None)
        parent_empty.empty_display_size = 0.02
        parent_empty.hide_viewport = True
        parent_empty.hide_render = True
        collection.objects.link(parent_empty)

    node_positions: dict[str, object] = {}
    objects_created: list[object] = []
    collision_context = _new_collision_context()
    annotation_context = {
        "plant_id": instance_id or "plant_01",
        "plant_role": instance_role,
    }
    stem_family = str(plant.metadata.get("stem_color_family", "green"))
    stem_material_key = {
        "green": "stem_green",
        "dark_green": "stem_dark_green",
        "drying_olive": "stem_drying_olive",
        "drying_brown": "stem_drying_brown",
    }.get(stem_family, "stem_green")
    petiole_material_key = "petiole_drying" if plant.condition == "drying" else "petiole_green"
    max_z = 0.0

    for axis in plant.axes:
        main_direction = Vector((0.05, -0.03, 1.0)).normalized()
        max_z = max(
            max_z,
            _build_axis_geometry(
                axis=axis,
                start=Vector((0.0, 0.0, 0.0)),
                parent_direction=main_direction,
                materials=materials,
                node_positions=node_positions,
                objects_created=objects_created,
                collision_context=collision_context,
                annotation_context=annotation_context,
                scale=cm_to_blender_unit,
                stem_material_key=stem_material_key,
                petiole_material_key=petiole_material_key,
            ),
        )

    if parent_empty is not None:
        transform = (
            Matrix.Translation(Vector(position))
            @ Matrix.Rotation(math.radians(rotation_deg), 4, "Z")
            @ Matrix.Diagonal((plant_scale, plant_scale, plant_scale, 1.0))
        )
        instance_transform = transform
        for obj in objects_created:
            _move_to_collection(obj, collection)
            obj.matrix_world = transform @ obj.matrix_world
        parent_empty.location = position
        parent_empty.rotation_euler = (0.0, 0.0, math.radians(rotation_deg))
        parent_empty.scale = (plant_scale, plant_scale, plant_scale)

    if add_ground:
        _add_ground_plane(materials)

    max_xy = _estimate_local_radius(node_positions)
    capacho_count = _count_fruiting_units(plant)
    main_stem_points = []
    if plant.axes:
        for node in plant.axes[0].nodes:
            local_point = node_positions.get(node.id)
            if local_point is None:
                continue
            world_point = instance_transform @ Vector(local_point)
            main_stem_points.append(tuple(round(float(value), 5) for value in world_point))

    return {
        "objects_created": len(objects_created),
        "node_positions": len(node_positions),
        "height": round(max_z * plant_scale, 4),
        "target": (
            round(position[0], 4),
            round(position[1], 4),
            round(max_z * plant_scale * 0.52, 4),
        ),
        "bounds_proxy": {
            "base": tuple(round(value, 4) for value in position),
            "height": round(max_z * plant_scale, 4),
            "canopy_radius": round(max_xy * plant_scale, 4),
            "capacho_count": capacho_count,
            "strict_collision": ["base", "main_stem", "capacho"],
            "allowed_visual_overlap": ["leaf", "leaf_to_capacho"],
        },
        "physical_collisions": collision_context["physical_collisions"],
        "visual_occlusions": collision_context["visual_occlusions"],
        "reproductive_pose_retries": collision_context["reproductive_pose_retries"],
        "main_stem_points": main_stem_points,
        "unit_scale": "1_cm_to_0.08_blender_units",
    }


def _build_axis_geometry(
    axis: Axis,
    start: object,
    parent_direction: object,
    materials: dict[str, object],
    node_positions: dict[str, object],
    objects_created: list[object],
    collision_context: dict[str, Any],
    annotation_context: dict[str, str],
    scale: float,
    stem_material_key: str,
    petiole_material_key: str,
) -> float:
    _, Vector = _blender_modules()
    direction = (
        Vector(axis.resolved_direction).normalized()
        if axis.resolved_direction is not None
        else _axis_direction(
            parent_direction,
            axis.azimuth_deg,
            axis.branch_angle_deg,
        )
    )
    current = Vector(start)
    max_z = current.z
    node_directions: dict[str, object] = {}

    for index, internode in enumerate(axis.internodes):
        direction = _bend_direction(
            direction,
            internode.bend_azimuth_deg,
            internode.bend_angle_deg,
        )
        direction = _apply_axis_load_deflection(
            direction,
            axis=axis,
            segment_index=index,
            segment_count=len(axis.internodes),
        )
        segment_end = current + direction * (internode.length_cm * scale)
        stem_radius = max(internode.radius_cm * scale, 0.008)
        stem_material = materials.get(stem_material_key, materials["stem"])
        stem = _create_sagging_curve_between(
            name=f"uchuva_{internode.id}",
            start=current,
            end=segment_end,
            radius=stem_radius,
            material=stem_material,
            sag_factor=(
                0.012 + axis.reproductive_load * 0.025
                if axis.order == 0
                else 0.045 + axis.reproductive_load * 0.115
            ),
        )
        _append_if_created(objects_created, stem)
        tag_annotation_object(
            stem,
            "stem",
            **annotation_context,
            organ_id=internode.id,
            organ_kind="axis_segment",
            axis_id=axis.id,
            axis_parent_node_id=axis.parent_node_id or "",
            internode_index=index,
            axis_order=axis.order,
        )
        _register_segment(
            collision_context,
            kind="stem",
            name=internode.id,
            start=current,
            end=segment_end,
            radius=stem_radius,
        )

        if index < len(axis.nodes):
            node = axis.nodes[index]
            node_positions[node.id] = segment_end
            node_directions[node.id] = direction.copy()
            if node.leaf is not None:
                created = _create_leaf_at_node(
                    node_position=segment_end,
                    axis_direction=direction,
                    leaf=node.leaf,
                    materials=materials,
                    collision_context=collision_context,
                    annotation_context=annotation_context,
                    scale=scale,
                    petiole_material_key=petiole_material_key,
                    parent_node_id=node.id,
                    axis_order=axis.order,
                )
                objects_created.extend(created)
            if node.reproductive_unit is not None:
                created = _create_reproductive_unit_at_node(
                    node_position=segment_end,
                    unit=node.reproductive_unit,
                    materials=materials,
                    collision_context=collision_context,
                    annotation_context=annotation_context,
                    scale=scale,
                    pedicel_material_key=petiole_material_key,
                    parent_node_id=node.id,
                    axis_order=axis.order,
                )
                objects_created.extend(created)

        current = segment_end
        max_z = max(max_z, current.z)

    for child_axis in axis.child_axes:
        child_start = node_positions.get(child_axis.parent_node_id)
        if child_start is None:
            continue
        max_z = max(
            max_z,
            _build_axis_geometry(
                axis=child_axis,
                start=child_start,
                parent_direction=node_directions.get(child_axis.parent_node_id, direction),
                materials=materials,
                node_positions=node_positions,
                objects_created=objects_created,
                collision_context=collision_context,
                annotation_context=annotation_context,
                scale=scale,
                stem_material_key=stem_material_key,
                petiole_material_key=petiole_material_key,
            ),
        )

    apex = _create_apex_marker(
        name=f"uchuva_{axis.id}_apex",
        location=current,
        radius=max(0.018 * (1.0 - 0.18 * axis.order), 0.008),
        material=materials.get(stem_material_key, materials["stem"]),
    )
    _append_if_created(objects_created, apex)
    tag_annotation_object(
        apex,
        "stem",
        **annotation_context,
        organ_id=f"{axis.id}_apex",
        organ_kind="axis_apex",
        axis_id=axis.id,
        axis_parent_node_id=axis.parent_node_id or "",
        internode_index=len(axis.internodes),
        axis_order=axis.order,
    )

    return max_z


def _create_leaf_at_node(
    node_position: object,
    axis_direction: object,
    leaf: Leaf,
    materials: dict[str, object],
    collision_context: dict[str, Any],
    annotation_context: dict[str, str],
    scale: float,
    petiole_material_key: str,
    parent_node_id: str,
    axis_order: int,
) -> list[object]:
    _, Vector = _blender_modules()
    radial = _radial_vector(leaf.azimuth_deg)
    angle = math.radians(leaf.insertion_angle_deg)
    direction = (axis_direction.normalized() * math.cos(angle) + radial * math.sin(angle))
    if direction.length < 1e-6:
        direction = radial
    direction = direction.normalized()

    petiole_length = leaf.petiole_length_cm * scale
    clearance_lift = max(0.0, float(leaf.clearance_lift_cm)) * scale
    if clearance_lift > 0.0 and petiole_length > 1e-9:
        lifted_target = direction * petiole_length + Vector(
            (0.0, 0.0, clearance_lift)
        )
        if lifted_target.length > 1e-9:
            direction = lifted_target.normalized()
    petiole_end = Vector(node_position) + direction * petiole_length
    petiole_radius = max(0.035 * scale, 0.004)
    petiole = _create_cylinder_between(
        name=f"uchuva_{leaf.id}_petiole",
        start=node_position,
        end=petiole_end,
        radius=petiole_radius,
        material=materials.get(petiole_material_key, materials["petiole"]),
        vertices=8,
    )
    _register_segment(
        collision_context,
        kind="petiole",
        name=leaf.id,
        start=node_position,
        end=petiole_end,
        radius=petiole_radius,
    )
    tag_annotation_object(
        petiole,
        "stem",
        **annotation_context,
        organ_id=f"{leaf.id}_petiole",
        organ_kind="petiole",
        parent_node_id=parent_node_id,
        axis_order=axis_order,
        orientation_adjustment_deg=leaf.orientation_adjustment_deg,
        clearance_lift_cm=leaf.clearance_lift_cm,
        clearance_lift_reason=leaf.clearance_lift_reason or "",
    )
    length = leaf.length_cm * scale
    width = leaf.width_cm * scale
    gravity_sag = _leaf_gravity_sag(direction, length)
    blade = _create_leaf_blade(
        name=f"uchuva_{leaf.id}",
        location=petiole_end,
        direction=direction,
        length=length,
        width=width,
        material=(
            materials.get("leaf_senescent", materials["leaf"])
            if leaf.senescence >= 0.22
            else materials["leaf"]
        ),
        edge_phase=math.radians(leaf.azimuth_deg),
        gravity_sag=gravity_sag,
        shape=leaf.shape,
        margin=leaf.margin,
        curl=leaf.curl,
        twist_deg=leaf.twist_deg,
        edge_damage=leaf.edge_damage,
    )
    midrib = _create_leaf_midrib_mesh(
        name=f"uchuva_{leaf.id}_midrib",
        location=petiole_end,
        direction=direction,
        length=length,
        gravity_sag=gravity_sag,
        base_radius=max(0.014 * scale, 0.003),
        material=materials["leaf_vein"],
    )
    _register_leaf_proxy(
        collision_context,
        name=leaf.id,
        base=petiole_end,
        direction=direction,
        length=length,
        width=width,
        gravity_sag=gravity_sag,
    )
    tag_annotation_object(
        blade,
        "leaf",
        **annotation_context,
        organ_id=leaf.id,
        axis_order=axis_order,
        orientation_adjustment_deg=leaf.orientation_adjustment_deg,
        clearance_lift_cm=leaf.clearance_lift_cm,
        clearance_lift_reason=leaf.clearance_lift_reason or "",
    )
    tag_annotation_object(
        midrib,
        "leaf",
        **annotation_context,
        organ_id=f"{leaf.id}_midrib",
        axis_order=axis_order,
        orientation_adjustment_deg=leaf.orientation_adjustment_deg,
        clearance_lift_cm=leaf.clearance_lift_cm,
        clearance_lift_reason=leaf.clearance_lift_reason or "",
    )
    return [obj for obj in (petiole, blade, midrib) if obj is not None]


def _create_reproductive_unit_at_node(
    node_position: object,
    unit: ReproductiveUnit,
    materials: dict[str, object],
    collision_context: dict[str, Any],
    annotation_context: dict[str, str],
    scale: float,
    pedicel_material_key: str,
    parent_node_id: str,
    axis_order: int,
) -> list[object]:
    _, Vector = _blender_modules()
    if unit.stage == "flower":
        radial = _radial_vector(unit.pedicel.azimuth_deg)
        direction = (radial * 0.9 + Vector((0.0, 0.0, 0.18))).normalized()
    else:
        # v3 poses are resolved globally in the morphology tree. Blender is a
        # strict interpreter and must not silently rotate the pedicel again.
        direction = _reproductive_direction(unit, 0.0, 0.0)

    pedicel_end = Vector(node_position) + direction * (unit.pedicel.length_cm * scale)
    created: list[object] = []
    pedicel_radius = max(0.028 * scale, 0.004)
    pedicel = _create_cylinder_between(
        name=f"uchuva_{unit.pedicel.id}",
        start=node_position,
        end=pedicel_end,
        radius=pedicel_radius,
        material=materials.get(pedicel_material_key, materials["petiole"]),
        vertices=8,
    )
    _append_if_created(created, pedicel)
    tag_annotation_object(
        pedicel,
        "stem",
        **annotation_context,
        organ_id=unit.pedicel.id,
        reproductive_id=unit.id,
        organ_kind="pedicel",
        parent_node_id=parent_node_id,
        axis_order=axis_order,
        orientation_adjustment_deg=unit.pedicel.orientation_adjustment_deg,
    )
    _register_segment(
        collision_context,
        kind="pedicel",
        name=unit.pedicel.id,
        start=node_position,
        end=pedicel_end,
        radius=pedicel_radius,
    )

    if unit.stage == "flower":
        flower = _create_flower_corolla(
            name=f"uchuva_{unit.id}_flower",
            location=pedicel_end,
            direction=direction,
            radius=0.16,
            material=materials["flower"],
        )
        _append_if_created(created, flower)
        tag_annotation_object(
            flower,
            "flower",
            **annotation_context,
            organ_id=f"{unit.id}_flower",
            reproductive_id=unit.id,
            maturity="flower",
            reproductive_stage=unit.stage,
            axis_order=axis_order,
        )
        return created

    calyx_center = pedicel_end
    calyx_length = 0.0
    calyx_radius = 0.0
    if unit.calyx is not None:
        calyx_length = unit.calyx.length_cm * scale
        calyx_radius = unit.calyx.radius_cm * scale
        calyx_center = pedicel_end + direction * (
            calyx_length * CALYX_CENTER_FROM_PEDICEL_FRACTION
        )
        calyx = create_calyx_mesh(
            name=f"uchuva_{unit.calyx.id}",
            length=calyx_length,
            width=calyx_radius * 2.0,
            ribs=unit.calyx.ribs,
            openness=unit.calyx.openness,
            inflation=unit.calyx.inflation,
            profile=unit.calyx.profile,
            tip_length_ratio=unit.calyx.tip_length_ratio,
            wrinkle=unit.calyx.wrinkle,
            asymmetry=unit.calyx.asymmetry,
            pubescence=unit.calyx.pubescence,
            vein_contrast=unit.calyx.vein_contrast,
            apical_darkening=unit.calyx.apical_darkening,
            maturity_progress=unit.calyx.maturity_progress,
            circularity_target=unit.calyx.circularity_target,
            turgor=unit.calyx.turgor,
            material_key=unit.calyx.material_key,
            seed=_stable_seed(unit.calyx.id),
            materials=materials,
            location=calyx_center,
            longitudinal_axis=-direction,
            annotation_context=annotation_context,
            reproductive_id=unit.id,
            calyx_state=unit.calyx.state,
            maturity=unit.maturity or "",
            reproductive_stage=unit.stage,
            axis_order=axis_order,
        )
        created.extend(calyx)
        _register_calyx_proxy(
            collision_context,
            name=unit.calyx.id,
            center=calyx_center,
            radius=_calyx_collision_radius(calyx_radius, calyx_length, unit.calyx.inflation),
            state=unit.calyx.state,
        )

    if unit.fruit is not None:
        material_key = "fruit_unripe"
        if unit.stage in {"mature_fruit_with_calyx", "exposed_fruit"}:
            material_key = "fruit_ripe"
        cover_fraction = unit.calyx.covers_fruit_fraction if unit.calyx else 0.0
        visible_scale = _visible_fruit_scale(unit.fruit.visibility, cover_fraction)
        hidden_by_closed_calyx = (
            unit.calyx is not None
            and unit.calyx.openness <= 0.001
            and unit.fruit.visibility == "hidden"
        )
        if unit.fruit.visibility == "partial":
            fruit_location = calyx_center + direction * (calyx_length * 0.16)
        elif unit.fruit.visibility == "visible":
            fruit_location = calyx_center + direction * (calyx_length * 0.30)
        else:
            fruit_location = calyx_center

        fruit = _create_uv_sphere(
            name=f"uchuva_{unit.fruit.id}",
            location=fruit_location,
            radius=unit.fruit.radius_cm * scale * visible_scale,
            material=materials[material_key],
            scale_tuple=(1.0, 0.96, 0.9),
            visible=not hidden_by_closed_calyx,
        )
        if hidden_by_closed_calyx:
            fruit["uchuva_hidden_inside_closed_calyx"] = True
        tag_annotation_object(
            fruit,
            "ignore",
            **annotation_context,
            organ_id=unit.fruit.id,
            reproductive_id=unit.id,
            calyx_state=unit.calyx_state or "",
            maturity=unit.maturity or "",
            reproductive_stage=unit.stage,
            annotation_visible=False,
            axis_order=axis_order,
        )
        _append_if_created(created, fruit)

    return created


def create_calyx_mesh(
    name: str,
    length: float,
    width: float,
    ribs: int,
    openness: float,
    inflation: float,
    material_key: str,
    seed: int,
    profile: str = "lantern_squash",
    tip_length_ratio: float = 0.12,
    wrinkle: float = 0.0,
    asymmetry: float = 0.0,
    pubescence: float = 0.5,
    vein_contrast: float = 0.5,
    apical_darkening: float = 0.0,
    maturity_progress: float = 0.0,
    circularity_target: float | None = None,
    turgor: float = 1.0,
    *,
    materials: dict[str, object] | None = None,
    location: object | None = None,
    longitudinal_axis: object | None = None,
    annotation_context: dict[str, str] | None = None,
    reproductive_id: str = "",
    calyx_state: str = "",
    maturity: str = "",
    reproductive_stage: str = "",
    axis_order: int = -1,
) -> list[object]:
    """Create an inflated uchuva calyx/capacho mesh with main surface ribs.

    The mesh captures only the main ribs that affect silhouette and 3D reading.
    Secondary venation and stains stay in generated 2D material maps instead
    of being modeled as dense geometry at this stage.
    """
    bpy, Vector = _blender_modules()
    rng = random.Random(seed)
    radius = max(width * 0.5, 0.035)
    length = max(radius * 2.10, min(length, radius * 3.10))
    ribs = 5
    openness = 0.0
    inflation = max(0.75, min(1.45, inflation))
    tip_length_ratio = max(0.06, min(0.20, tip_length_ratio))
    wrinkle = max(0.0, min(0.40, wrinkle))
    asymmetry = max(0.0, min(0.14, asymmetry))
    maturity_progress = max(0.0, min(1.0, maturity_progress))
    turgor = max(0.5, min(1.1, turgor))
    location_vector = Vector(location or (0.0, 0.0, 0.0))
    material_map = materials or {}
    calyx_material = material_map.get(material_key) or material_map.get("calyx")

    mesh = bpy.data.meshes.new(f"{name}_mesh")
    vertices: list[tuple[float, float, float]] = []
    faces: list[tuple[int, ...]] = []
    rings = 24
    segments = ribs * 12
    window_center = rng.uniform(0.0, 2.0 * math.pi)
    window_half_angle = max(0.0, openness - 0.18) * math.pi * 0.92
    asymmetry_phase = rng.uniform(0.0, math.tau)
    valley_depth_range = {
        "inflated_green": (0.014, 0.024),
        "transitioning_yellow": (0.0135, 0.0235),
        "straw_yellow": (0.013, 0.023),
        "dry_deteriorated": (0.012, 0.021),
    }.get(calyx_state, (0.013, 0.023))
    intercostal_valley_depth = rng.uniform(*valley_depth_range)
    structural_rib_amplitude = rng.uniform(0.055, 0.080)
    sepal_width_offsets = [rng.uniform(-0.038, 0.038) for _ in range(ribs)]
    sepal_axial_offsets = [rng.uniform(-0.018, 0.018) for _ in range(ribs)]
    fold_count = min(3, int(round(maturity_progress * 3.0)))
    circularity_deformation = (
        max(0.0, min(0.20, 0.59 - float(circularity_target)))
        if circularity_target is not None
        else 0.0
    )
    local_folds = [
        {
            "angle": rng.uniform(0.0, math.tau),
            "t": rng.uniform(0.30, 0.78),
            "angle_sigma": rng.uniform(0.12, 0.24),
            "t_sigma": rng.uniform(0.08, 0.17),
            "depth": rng.uniform(0.45, 0.80) * min(0.075, wrinkle * 0.22),
        }
        for _ in range(fold_count)
    ]

    for ring_index in range(rings + 1):
        t = ring_index / rings
        z = (0.5 - t) * length
        taper = _calyx_profile_radius_factor(
            t, openness, inflation, profile, calyx_state
        )

        for segment_index in range(segments):
            angle = 2.0 * math.pi * segment_index / segments
            rib_phase = math.cos(angle * ribs)
            rib_crest = max(0.0, rib_phase) ** 6
            intercostal_valley = max(0.0, -rib_phase) ** 4
            ribbed = (
                1.0
                + structural_rib_amplitude * rib_crest
                - intercostal_valley_depth * intercostal_valley
            )
            sepal_coordinate = angle * ribs / math.tau
            sepal_left = int(math.floor(sepal_coordinate)) % ribs
            sepal_right = (sepal_left + 1) % ribs
            sepal_fraction = sepal_coordinate - math.floor(sepal_coordinate)
            smooth_fraction = sepal_fraction * sepal_fraction * (3.0 - 2.0 * sepal_fraction)
            local_sepal_offset = (
                sepal_width_offsets[sepal_left] * (1.0 - smooth_fraction)
                + sepal_width_offsets[sepal_right] * smooth_fraction
            )
            axial_offset = (
                sepal_axial_offsets[sepal_left] * (1.0 - smooth_fraction)
                + sepal_axial_offsets[sepal_right] * smooth_fraction
            ) * math.sin(math.pi * t) ** 1.3
            asymmetric = (
                1.0
                + asymmetry * 0.55 * math.cos(angle - asymmetry_phase)
                + local_sepal_offset * math.sin(math.pi * t)
                + axial_offset
            )
            localized_fold = 1.0
            for fold in local_folds:
                angular_distance = math.atan2(
                    math.sin(angle - fold["angle"]),
                    math.cos(angle - fold["angle"]),
                )
                fold_distance = (
                    (angular_distance / fold["angle_sigma"]) ** 2
                    + ((t - fold["t"]) / fold["t_sigma"]) ** 2
                )
                localized_fold -= fold["depth"] * math.exp(-0.5 * fold_distance)
            maturity_asymmetry = 1.0 + circularity_deformation * 0.18 * math.cos(
                angle - asymmetry_phase * 0.63
            )
            local_radius = (
                radius
                * taper
                * ribbed
                * asymmetric
                * maturity_asymmetry
                * localized_fold
            )
            tip_wave = 0.0
            if t > 0.80:
                distal = (t - 0.80) / 0.20
                tip_wave = length * tip_length_ratio * distal**1.7 * (
                    0.16 + 0.34 * max(0.0, math.cos(angle * ribs))
                )
            x = math.cos(angle) * local_radius
            y = math.sin(angle) * local_radius
            vertices.append((x, y, z - tip_wave))

    top_center = len(vertices)
    vertices.append((0.0, 0.0, 0.5 * length))
    bottom_center = len(vertices)
    vertices.append((0.0, 0.0, -0.5 * length - length * tip_length_ratio * 0.34))

    for ring_index in range(rings):
        for segment_index in range(segments):
            a = ring_index * segments + segment_index
            b = ring_index * segments + (segment_index + 1) % segments
            c = (ring_index + 1) * segments + (segment_index + 1) % segments
            d = (ring_index + 1) * segments + segment_index
            if _is_open_window_face(
                segment_index,
                segments,
                ring_index,
                rings,
                window_center,
                window_half_angle,
            ):
                continue
            faces.append((a, b, c, d))

    for segment_index in range(segments):
        next_segment = (segment_index + 1) % segments
        faces.append((top_center, next_segment, segment_index))
        bottom_a = rings * segments + segment_index
        bottom_b = rings * segments + next_segment
        faces.append((bottom_center, bottom_a, bottom_b))

    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    _assign_calyx_uvs(mesh, rings, segments, top_center, bottom_center)
    for polygon in mesh.polygons:
        polygon.use_smooth = True

    husk = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(husk)
    husk.location = location_vector
    if calyx_material is not None:
        husk.data.materials.append(calyx_material)
    husk["uchuva_calyx_openness"] = openness
    husk["uchuva_material_key"] = material_key
    husk["uchuva_calyx_profile"] = profile
    husk["uchuva_calyx_wrinkle"] = wrinkle
    husk["uchuva_calyx_pubescence"] = pubescence
    husk["uchuva_texture_variant"] = material_key
    husk["uchuva_vein_contrast"] = float(vein_contrast)
    husk["uchuva_apical_darkening"] = float(apical_darkening)
    husk["uchuva_maturity_progress"] = float(maturity_progress)
    husk["uchuva_circularity_target"] = (
        float(circularity_target) if circularity_target is not None else -1.0
    )
    husk["uchuva_turgor"] = float(turgor)
    husk["uchuva_intercostal_valley_depth"] = round(intercostal_valley_depth, 4)
    husk["uchuva_surface_fold_model"] = "localized_nonperiodic_v1"
    husk["uchuva_macro_periodic_wrinkles"] = False
    if longitudinal_axis is not None:
        _orient_local_z_to(husk, longitudinal_axis)
    tag_annotation_object(
        husk,
        "calyx",
        **(annotation_context or {}),
        organ_id=name,
        reproductive_id=reproductive_id,
        calyx_state=calyx_state,
        maturity=maturity,
        reproductive_stage=reproductive_stage,
        axis_order=axis_order,
    )

    # Main sepal folds remain a shallow part of the shell silhouette.  Dense
    # vascular geometry is supplied by the generated normal/albedo maps, so
    # no detached tube-like rib curves are created in v2.
    return [husk]


def _calyx_profile_radius_factor(
    t: float,
    openness: float,
    inflation: float,
    profile: str = "lantern_squash",
    calyx_state: str = "",
) -> float:
    exponent = 0.46 if profile == "lantern_squash" else 0.68
    lantern = math.sin(math.pi * t) ** exponent
    shoulder = 0.12 + 0.88 * lantern
    if t < 0.14:
        shoulder *= 0.48 + 3.70 * t
    if t > 0.76:
        distal = (t - 0.76) / 0.24
        shoulder *= max(0.07, (1.0 - distal) ** 0.58)
    if profile == "lantern_squash":
        shoulder *= 1.0 + 0.035 * math.exp(-((t - 0.53) / 0.24) ** 2)
    return max(shoulder * inflation, 0.04 + openness * 0.2)


def _is_open_window_face(
    segment_index: int,
    segments: int,
    ring_index: int,
    rings: int,
    window_center: float,
    window_half_angle: float,
) -> bool:
    if window_half_angle <= 0.0:
        return False
    t_mid = (ring_index + 0.5) / rings
    if t_mid < 0.32:
        return False
    angle = 2.0 * math.pi * (segment_index + 0.5) / segments
    diff = abs(math.atan2(math.sin(angle - window_center), math.cos(angle - window_center)))
    return diff < window_half_angle


def _create_surface_rib_curve(
    name: str,
    angle: float,
    length: float,
    radius: float,
    openness: float,
    inflation: float,
    profile: str,
    calyx_state: str,
    tip_length_ratio: float,
    bevel_depth: float,
    material: object | None,
    location: object,
    longitudinal_axis: object | None,
) -> object:
    bpy, Vector = _blender_modules()
    curve = bpy.data.curves.new(f"{name}_curve", type="CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = 2
    curve.bevel_depth = bevel_depth
    curve.bevel_resolution = 2

    points = []
    for index in range(13):
        t = 0.05 + 0.94 * index / 12
        local_radius = radius * _calyx_profile_radius_factor(
            t, openness, inflation, profile, calyx_state
        ) * 1.155
        distal = max(0.0, (t - 0.80) / 0.20)
        z = (0.5 - t) * length - length * tip_length_ratio * distal**1.7
        points.append((math.cos(angle) * local_radius, math.sin(angle) * local_radius, z, 1.0))

    spline = curve.splines.new("POLY")
    spline.points.add(len(points) - 1)
    for point, coordinates in zip(spline.points, points):
        point.co = coordinates

    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    obj.location = Vector(location)
    if material is not None:
        curve.materials.append(material)
    if longitudinal_axis is not None:
        _orient_local_z_to(obj, longitudinal_axis)
    return obj


def _create_leaf_blade(
    name: str,
    location: object,
    direction: object,
    length: float,
    width: float,
    material: object,
    edge_phase: float,
    gravity_sag: float,
    shape: str,
    margin: str,
    curl: float,
    twist_deg: float,
    edge_damage: float,
) -> object:
    bpy, Vector = _blender_modules()
    mesh = bpy.data.meshes.new(f"{name}_mesh")
    vertices: list[tuple[float, float, float]] = []
    faces: list[tuple[int, ...]] = []
    segments = 32

    vertices.append(_leaf_centerline_point(0.0, length, gravity_sag))
    for index in range(segments + 1):
        t = 0.055 + (0.945 * index / segments)
        center_x, y, z = _leaf_centerline_point(t, length, gravity_sag)
        profile, basal_lobes = _leaf_shape_profile(shape, t)
        margin_amplitude = {
            "entire": 0.006,
            "slightly_toothed": 0.020,
            "irregular": 0.032,
        }.get(margin, 0.012)
        margin_noise = (
            0.62 * math.sin(edge_phase + t * 10.7)
            + 0.38 * math.sin(edge_phase * 0.71 + t * 23.3)
        ) * math.sin(math.pi * t) ** 1.4
        waviness = 1.0 + margin_amplitude * margin_noise
        asymmetry = 1.0 - 0.08 * t + 0.025 * math.sin(edge_phase + t * 4.1)
        half_width = 0.5 * width * profile * waviness
        left_width = half_width * basal_lobes
        right_width = half_width * basal_lobes * asymmetry
        damage_envelope = math.sin(math.pi * t) ** 1.8
        left_damage = edge_damage * damage_envelope * max(
            0.0, math.sin(edge_phase * 1.9 + t * 29.0)
        ) ** 8
        right_damage = edge_damage * damage_envelope * max(
            0.0, math.sin(edge_phase * 2.3 + t * 31.0 + 1.7)
        ) ** 8
        left_width *= 1.0 - min(0.55, left_damage)
        right_width *= 1.0 - min(0.55, right_damage)
        twist_angle = math.radians(twist_deg) * t
        cup = max(-0.20, min(0.20, curl)) * half_width * 0.28 * math.sin(math.pi * t)
        left_dx = -left_width * math.cos(twist_angle)
        right_dx = right_width * math.cos(twist_angle)
        left_dz = -left_width * math.sin(twist_angle) + cup
        right_dz = right_width * math.sin(twist_angle) + cup * 0.88
        vertices.append((center_x + left_dx, y, z + left_dz))
        vertices.append((center_x + right_dx, y, z + right_dz))

    faces.append((0, 1, 2))
    for index in range(segments):
        left_0 = 1 + index * 2
        right_0 = left_0 + 1
        left_1 = left_0 + 2
        right_1 = left_0 + 3
        faces.append((left_0, right_0, right_1, left_1))

    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    _assign_leaf_uvs(mesh, length, width)
    for polygon in mesh.polygons:
        polygon.use_smooth = True

    blade = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(blade)
    direction = Vector(direction)
    if direction.length < 1e-6:
        direction = Vector((0.0, 1.0, 0.0))
    blade.rotation_euler = direction.normalized().to_track_quat("Y", "Z").to_euler()
    blade.location = location
    blade.data.materials.append(material)

    solidify = blade.modifiers.new(name="leaf_minimum_thickness", type="SOLIDIFY")
    solidify.thickness = max(0.00012, min(0.00035, width * 0.004))
    solidify.offset = 0.0
    blade["uchuva_leaf_thickness_status"] = "literature_bounded_manual_initial_guess"
    blade["uchuva_leaf_margin_model"] = "low_amplitude_irregular_v1"
    return blade


def _leaf_shape_profile(shape: str, t: float) -> tuple[float, float]:
    # Smooth beta-like polynomial envelope with no periodic term.
    u = max(0.0, min(1.0, t))
    envelope = max(0.0, 4.0 * u * (1.0 - u))
    if shape == "deltoid_ovate":
        profile = (envelope**0.56) * (1.34 - 0.70 * u)
        basal_lobes = 1.0 + 0.10 * math.exp(-((t - 0.16) / 0.11) ** 2)
    elif shape == "ovate_cordate":
        profile = (envelope**0.42) * (1.22 - 0.52 * u)
        basal_lobes = 1.0 + 0.32 * math.exp(-((t - 0.12) / 0.085) ** 2)
    else:
        profile = (envelope**0.48) * (1.18 - 0.48 * u)
        basal_lobes = 1.0 + 0.12 * math.exp(-((t - 0.14) / 0.10) ** 2)
    return profile, basal_lobes


def _create_leaf_midrib_mesh(
    name: str,
    location: object,
    direction: object,
    length: float,
    gravity_sag: float,
    base_radius: float,
    material: object,
) -> object:
    bpy, Vector = _blender_modules()
    mesh = bpy.data.meshes.new(f"{name}_mesh")
    vertices: list[tuple[float, float, float]] = []
    faces: list[tuple[int, ...]] = []
    rings = 12
    sides = 7

    for ring_index in range(rings + 1):
        t = ring_index / rings
        center_x, center_y, center_z = _leaf_centerline_point(t, length, gravity_sag)
        vein_radius = max(base_radius * (1.0 - 0.92 * t), base_radius * 0.08)
        for side_index in range(sides):
            angle = 2.0 * math.pi * side_index / sides
            vertices.append(
                (
                    center_x + math.cos(angle) * vein_radius,
                    center_y,
                    center_z + math.sin(angle) * vein_radius,
                )
            )

    for ring_index in range(rings):
        for side_index in range(sides):
            a = ring_index * sides + side_index
            b = ring_index * sides + (side_index + 1) % sides
            c = (ring_index + 1) * sides + (side_index + 1) % sides
            d = (ring_index + 1) * sides + side_index
            faces.append((a, b, c, d))

    tip_center = len(vertices)
    tip_x, tip_y, tip_z = _leaf_centerline_point(1.0, length, gravity_sag)
    vertices.append((tip_x, tip_y + base_radius * 1.6, tip_z))
    last_ring_start = rings * sides
    for side_index in range(sides):
        faces.append(
            (
                last_ring_start + side_index,
                last_ring_start + (side_index + 1) % sides,
                tip_center,
            )
        )

    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    for polygon in mesh.polygons:
        polygon.use_smooth = True

    midrib = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(midrib)
    direction = Vector(direction)
    if direction.length < 1e-6:
        direction = Vector((0.0, 1.0, 0.0))
    midrib.rotation_euler = direction.normalized().to_track_quat("Y", "Z").to_euler()
    midrib.location = Vector(location)
    midrib.data.materials.append(material)
    return midrib


def _leaf_centerline_point(t: float, length: float, gravity_sag: float) -> tuple[float, float, float]:
    t = max(0.0, min(1.0, t))
    droop = gravity_sag * (t**2.0)
    return (0.0, t * length, -droop)


def _assign_leaf_uvs(mesh: object, length: float, width: float) -> None:
    if length <= 0.0 or width <= 0.0:
        return
    uv_layer = mesh.uv_layers.new(name="leaf_uv")
    for polygon in mesh.polygons:
        for loop_index in polygon.loop_indices:
            vertex = mesh.vertices[mesh.loops[loop_index].vertex_index].co
            uv_layer.data[loop_index].uv = (
                max(0.0, min(1.0, 0.5 + vertex.x / max(width, 1e-6))),
                max(0.0, min(1.0, vertex.y / max(length, 1e-6))),
            )


def _assign_calyx_uvs(
    mesh: object,
    rings: int,
    segments: int,
    top_center: int,
    bottom_center: int,
) -> None:
    """Unwrap the inflated husk as a seamless cylindrical vascular sheet."""
    uv_layer = mesh.uv_layers.new(name="calyx_uv")
    surface_vertex_count = (rings + 1) * segments
    for polygon in mesh.polygons:
        surface_segments = [
            vertex_index % segments
            for vertex_index in polygon.vertices
            if vertex_index < surface_vertex_count
        ]
        crosses_seam = bool(surface_segments) and (
            max(surface_segments) - min(surface_segments) > segments // 2
        )
        surface_uvs: list[tuple[float, float]] = []
        for vertex_index in polygon.vertices:
            if vertex_index >= surface_vertex_count:
                continue
            ring_index = vertex_index // segments
            segment_index = vertex_index % segments
            adjusted_segment = (
                segments
                if crosses_seam and segment_index == 0
                else segment_index
            )
            surface_uvs.append(
                (adjusted_segment / segments, ring_index / max(1, rings))
            )
        center_u = (
            sum(value[0] for value in surface_uvs) / len(surface_uvs)
            if surface_uvs
            else 0.5
        )
        for loop_index in polygon.loop_indices:
            vertex_index = mesh.loops[loop_index].vertex_index
            if vertex_index == top_center:
                uv = (center_u, 0.0)
            elif vertex_index == bottom_center:
                uv = (center_u, 1.0)
            else:
                ring_index = vertex_index // segments
                segment_index = vertex_index % segments
                adjusted_segment = (
                    segments
                    if crosses_seam and segment_index == 0
                    else segment_index
                )
                uv = (
                    adjusted_segment / segments,
                    ring_index / max(1, rings),
                )
            uv_layer.data[loop_index].uv = uv


def _create_cylinder_between(
    name: str,
    start: object,
    end: object,
    radius: float,
    material: object,
    vertices: int = 12,
) -> object | None:
    bpy, Vector = _blender_modules()
    start = Vector(start)
    end = Vector(end)
    direction = end - start
    length = direction.length
    if length < 1e-6:
        return None

    bpy.ops.mesh.primitive_cylinder_add(
        vertices=vertices,
        radius=radius,
        depth=length,
        location=(start + end) / 2.0,
    )
    cylinder = bpy.context.object
    cylinder.name = name
    cylinder.data.name = f"{name}_mesh"
    cylinder.rotation_euler = direction.to_track_quat("Z", "Y").to_euler()
    cylinder.data.materials.append(material)
    _shade_smooth(cylinder)
    return cylinder


def _create_sagging_curve_between(
    name: str,
    start: object,
    end: object,
    radius: float,
    material: object,
    sag_factor: float,
    points_count: int = 6,
) -> object | None:
    bpy, Vector = _blender_modules()
    start = Vector(start)
    end = Vector(end)
    direction = end - start
    length = direction.length
    if length < 1e-6:
        return None

    flatness = math.sqrt(direction.x**2 + direction.y**2) / length
    sag = length * sag_factor * (flatness**1.35)
    curve = bpy.data.curves.new(f"{name}_curve", type="CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = 3
    curve.bevel_depth = radius
    curve.bevel_resolution = 3

    spline = curve.splines.new("POLY")
    spline.points.add(points_count - 1)
    for index, point in enumerate(spline.points):
        t = index / (points_count - 1)
        position = start.lerp(end, t)
        position.z -= sag * math.sin(math.pi * t)
        point.co = (position.x, position.y, position.z, 1.0)

    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    if material is not None:
        curve.materials.append(material)
    return obj


